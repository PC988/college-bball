const CONF_TIER = { ACC: 'power', 'Big Ten': 'power', 'Big 12': 'power', SEC: 'power', 'Big East': 'power',
  'Atlantic 10': 'mid', American: 'mid', 'Mountain West': 'mid', WCC: 'mid', 'Missouri Valley': 'mid',
  Ivy: 'low', SWAC: 'low',
  MAC: 'mid', 'Sun Belt': 'mid', 'Conference USA': 'mid', CAA: 'mid', 'Big West': 'mid',
  'America East': 'low', ASUN: 'low', 'Big Sky': 'low', 'Big South': 'low', Horizon: 'low', MAAC: 'low', MEAC: 'low',
  NEC: 'low', OVC: 'low', Patriot: 'low', SoCon: 'low', Southland: 'low', Summit: 'low', WAC: 'low' };

const STYLES = ['motion', 'pick_and_roll', 'post_up', 'iso', 'princeton', 'run_and_gun', 'pack_line', 'zone_heavy'];
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
const slug = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

const schools = [];
const conferences = [];
for (const [conf, rows] of Object.entries(C)) {
  const confId = slug(conf);
  conferences.push({ id: confId, name: conf, level: CONF_TIER[conf] });
  for (const [name, abbr, state, tier, prestige, academic, enrollK, control, religion] of rows) {
    const id = slug(name);
    const rng = makeRng(hashString('school:' + id));
    const size = enrollK < 8 ? 'small' : enrollK < 25 ? 'medium' : 'large';
    // party: big publics high, religious and elite academics lower
    let party = 40 + enrollK * 0.7 + (control === 'U' ? 10 : 0) - (religion ? 15 : 0) - (academic - 70) * 0.4 + rng.int(-8, 8);
    if (religion === 'LDS' || religion === 'Baptist') party -= 20;
    // NIL budget in $ thousands per year, scales hard with prestige and conference level
    const levelMult = { power: 1, mid: 0.35, low: 0.08 }[CONF_TIER[conf]];
    const nil = Math.max(10, Math.round((prestige ** 2.2 / 100) * levelMult * (0.85 + rng.next() * 0.3)) * 10);
    const tempo = clamp(Math.round(68 + rng.normal() * 3.5), 60, 76); // possessions per 40 min
    schools.push({
      id, name, abbr, conference: confId, state, tier, prestige,
      nilBudget: nil, // $K per year
      size, enrollment: Math.round(enrollK * 1000), control: control === 'P' ? 'private' : 'public',
      religious: religion || null, academic, party: clamp(Math.round(party), 5, 99),
      facilities: clamp(Math.round(prestige * 0.8 + levelMult * 15 + rng.int(-6, 6)), 5, 99),
      coachingStyle: STYLES[rng.int(0, STYLES.length - 1)],
      tempo,
    });
  }
}

writeFileSync(new URL('../data/schools.json', import.meta.url),
  JSON.stringify({ version: 1, conferences, schools }, null, 1));
console.log(`wrote ${schools.length} schools in ${conferences.length} conferences`);
