// Bundles web/ + src/ into one self-contained HTML file, plus the installable phone version.
//   dist/recruiting.html, dist/College-Hoops-Manager.html  single file, double-click to play offline on a computer
//   index.html + sw.js + manifest.webmanifest + icons/      the PWA served by GitHub Pages (Add to Home Screen)
// Needs esbuild: npm i -D esbuild (or NODE_PATH pointing at an install).
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('..', import.meta.url).pathname;
const out = await build({ entryPoints: [root + 'web/app.js'], bundle: true, format: 'esm', minify: true, write: false, target: 'es2020' });
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = readFileSync(root + 'web/style.css', 'utf8');
let html = readFileSync(root + 'web/index.html', 'utf8');
html = html.replace('<link rel="stylesheet" href="style.css">', `<style>${css}</style>`);
html = html.replace('<script type="module" src="app.js"></script>', () => `<script type="module">${js}</script>`);
mkdirSync(root + 'dist', { recursive: true });
writeFileSync(root + 'dist/recruiting.html', html);
writeFileSync(root + 'dist/College-Hoops-Manager.html', html);
console.log(`dist/recruiting.html ${(html.length / 1024).toFixed(0)} KB`);

// ---- PWA ----
const head = `<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="icons/icon-180.png">
<link rel="icon" type="image/png" href="icons/icon-192.png">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<meta name="apple-mobile-web-app-title" content="Hoops Manager">
<script>if ('serviceWorker' in navigator && location.protocol.startsWith('http')) addEventListener('load', () => navigator.serviceWorker.register('sw.js', { updateViaCache: 'none' }));</script>
</head>`;
const pwa = html.replace('</head>', head);
writeFileSync(root + 'index.html', pwa);
const version = createHash('sha1').update(pwa).digest('hex').slice(0, 10);
const files = ['./', 'index.html', 'manifest.webmanifest', 'icons/icon-180.png', 'icons/icon-192.png', 'icons/icon-512.png'];
writeFileSync(root + 'sw.js', `// Generated by tools/bundle-web.mjs. Caches the whole game so it runs with no connection.
// Cache-first for instant offline launch; a new build ships a new version, which downloads in the background
// and takes over on the next launch.
const CACHE = 'hoops-${version}';
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  // The page itself: network first (skipping the HTTP cache) so a new version shows on the very next open; cached copy when offline.
  const page = e.request.mode === 'navigate' || new URL(e.request.url).pathname.endsWith('/index.html');
  if (page) {
    e.respondWith(fetch(e.request, { cache: 'no-cache' }).then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put('index.html', copy)); } return res; })
      .catch(() => caches.match('index.html')));
    return;
  }
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).catch(() => caches.match('index.html'))));
});
`);
writeFileSync(root + 'manifest.webmanifest', JSON.stringify({
  name: 'College Hoops Manager', short_name: 'Hoops Manager', start_url: './', scope: './', display: 'standalone', orientation: 'portrait',
  background_color: '#14284b', theme_color: '#1565c0',
  icons: [{ src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' }, { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' }, { src: 'icons/icon-180.png', sizes: '180x180', type: 'image/png' }],
}, null, 2));
console.log(`index.html (PWA) + sw.js ${version}`);
